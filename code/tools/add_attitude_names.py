def main():
    path = DATA_DIR / "attitudes.json"
    data = json.loads(path.read_text(encoding='utf-8'))

    named = 0
    missing = []

    for att in data["attitudes"]:
        att_id = att["id"]
        if att_id in NAMES:
            att["narrative_name"] = NAMES[att_id]
            named += 1
        else:
            missing.append(att_id)
            att["narrative_name"] = att_id  # fallback

    # ── 验证 ──
    print(f"命名完成: {named}/{len(data['attitudes'])} 条目")
    if missing:
        print(f"⚠ 缺失命名 ({len(missing)}): {missing}")

    # ── 去重检查 ──
    name_counts = {}
    for att in data["attitudes"]:
        nm = att["narrative_name"]
        name_counts[nm] = name_counts.get(nm, 0) + 1
    dups = {k: v for k, v in name_counts.items() if v > 1}
    if dups:
        print(f"⚠ 重名 ({len(dups)}): {dups}")

    # ── 写入 ──
    backup_path = path.with_suffix(".json.bak")
    path.rename(backup_path)
    path.write_text(
        json.dumps(data, ensure_ascii=False, indent=2),
        encoding='utf-8'
    )
    print(f"✓ 写入 {path} (备份: {backup_path})")

    # ── 按驱动分组预览 ──
    print("\n── 按驱动分组预览 ──")
    drives_order = ["反射", "惩罚", "奖励", "道德", "文化", "价值", "照护"]
    for drive in drives_order:
        entries = [att for att in data["attitudes"] if drive in att["id"]]
        names = [f"{att['emotion']}→{att['narrative_name']}" for att in entries]
        print(f"  {drive}: {', '.join(names)}")


if __name__ == '__main__':
    main()
